"""Database utilities (a composition root: builds the infra concretes).

    uv run python scripts/db.py schema > supabase/migrations/20261007000001_schema.sql   # Postgres DDL of every table
    uv run python scripts/db.py import            # load the course (sheets + theory) into DATABASE_URL
    uv run python scripts/db.py import-generats   # load the pre-generated documents and quizzes (backend/generats)
    uv run python scripts/db.py stats             # row counts

DATABASE_URL defaults to SQLite at data/tutor.db (see backend/settings).
"""

import asyncio
import sys

from dotenv import load_dotenv
from sqlalchemy import func
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from sqlmodel import SQLModel, select

from core.course.application.course_importer import CourseImporter
from core.course.infra.sqlmodel_repository import SQLModelCourseRepository
from core.course.infra.yaml_course_source import YamlCourseSource
from core.mistakes.application.pregenerated_importer import PregeneratedImporter as MistakesImporter
from core.mistakes.infra.json_file_source import JsonFileMistakeSource
from core.mistakes.infra.sqlmodel_repository import SQLModelMistakeExerciseRepository
from core.quizzes.application.pregenerated_importer import PregeneratedImporter as QuizzesImporter
from core.quizzes.infra.json_quiz_files import JsonQuizFiles
from core.quizzes.infra.sqlmodel_repository import SQLModelQuizRepository
from core.shared.storage.session_provider import SQLModelSessionProvider, create_schema_if_sqlite, make_engine
from core.shared.storage.table_registry import register_all_tables
from settings import BACKEND_DIR, ROOT_DIR, Config


def schema() -> str:
    register_all_tables()
    out = ["-- Generated by scripts/db.py schema from the SQLModel tables in backend/core. Do not edit by hand.", ""]
    dialect = postgresql.dialect()
    for table in SQLModel.metadata.sorted_tables:
        out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for ix in sorted(table.indexes, key=lambda i: str(i.name)):  # a set: sort for a stable migration
            out.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
        # Supabase exposes tables through its public API: enable RLS with no policies, so only the server
        # (direct Postgres connection, owner role) can read or write. The anon/public key sees nothing.
        out.append(f"ALTER TABLE {table.name} ENABLE ROW LEVEL SECURITY;")
        out.append("")
    return "\n".join(out)


async def _provider() -> SQLModelSessionProvider:
    register_all_tables()
    engine = make_engine(Config().async_database_url)
    await create_schema_if_sqlite(engine)
    return SQLModelSessionProvider(engine)


async def import_course() -> None:
    sessions = await _provider()
    source = YamlCourseSource(BACKEND_DIR / "exercicis", BACKEND_DIR / "teoria")
    print((await CourseImporter(source, SQLModelCourseRepository(sessions)).import_course()).model_dump())
    await sessions.engine.dispose()


async def import_generated() -> None:
    sessions = await _provider()
    generated = BACKEND_DIR / "generats"
    mistakes = await MistakesImporter(
        JsonFileMistakeSource(generated / "errades"), SQLModelMistakeExerciseRepository(sessions)
    ).import_all()
    quizzes = await QuizzesImporter(JsonQuizFiles(generated / "afirmacions"), SQLModelQuizRepository(sessions)).import_all()
    print(f"{mistakes} mistake documents and {quizzes} quizzes imported")
    await sessions.engine.dispose()


async def stats() -> None:
    sessions = await _provider()
    async with sessions.begin() as session:
        for table in SQLModel.metadata.sorted_tables:
            count = (await session.exec(select(func.count()).select_from(table))).one()
            print(f"{table.name:20s} {count}")
    await sessions.engine.dispose()


COMMANDS = {
    "schema": lambda: print(schema()),
    "import": lambda: asyncio.run(import_course()),
    "import-generats": lambda: asyncio.run(import_generated()),
    "stats": lambda: asyncio.run(stats()),
}

if __name__ == "__main__":
    load_dotenv(ROOT_DIR / ".env")
    command = sys.argv[1] if len(sys.argv) > 1 else "stats"
    if command not in COMMANDS:
        sys.exit(f"usage: db.py {{{'|'.join(COMMANDS)}}}")
    COMMANDS[command]()
