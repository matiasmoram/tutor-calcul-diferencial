KNOWN_COMMANDS = _COURSE | _KATEX

# "\\" is a row break, not a command: consume it first, or "\\y^2" would read as a command "\y". A row may start
# with a variable ("\\x=0" in \substack, "\\y^2" in pmatrix), but "\\subseteq" outside an environment is a command
# whose backslash the model escaped twice (seen in gpt-5.6-luna output), which KaTeX shows as a break + plain text.
_TOKEN = re.compile(r"\\begin\{[^}]*\}|\\end\{[^}]*\}|\\\\([A-Za-z]+)?|\\([A-Za-z]+)")


def unknown_commands(text: str) -> set[str]:
    """The LaTeX commands in `text` outside the vocabulary, e.g. {"fterm"} for "$e^{\\fterm{0.2}}$", and doubled
    backslashes before a word outside an environment, reported with both backslashes ("\\\\subseteq")."""
    unknown: set[str] = set()
    depth = 0
    for m in _TOKEN.finditer(text):
        token = m.group()
        if token.startswith("\\begin{"):
            depth += 1
        elif token.startswith("\\end{"):
            depth = max(0, depth - 1)
        elif token.startswith("\\\\"):
            if m.group(1) in KNOWN_COMMANDS and len(m.group(1)) > 2 and depth == 0:
                unknown.add("\\" + m.group(1))
        elif m.group(2) not in KNOWN_COMMANDS:
            unknown.add(m.group(2))
    return unknown
