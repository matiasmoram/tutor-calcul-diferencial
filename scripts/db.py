"""Database utilities.

    python scripts/db.py schema > supabase/migrations/<timestamp>_init.sql   # Postgres DDL from backend/tutor/db.py
    python scripts/db.py import                                                # load sheets + theory into DATABASE_URL
    python scripts/db.py import-generats                                       # load backend/generats/*/ JSON caches
    python scripts/db.py stats                                                 # row counts

DATABASE_URL defaults to SQLite at data/tutor.db (see backend/tutor/db.py).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from sqlalchemy import func, select  # noqa: E402
from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from tutor import db  # noqa: E402


def schema() -> str:
    out = ["-- Generated by scripts/db.py schema from backend/tutor/db.py. Do not edit by hand.", ""]
    dialect = postgresql.dialect()
    for table in db.meta.sorted_tables:
        out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for ix in sorted(table.indexes, key=lambda i: i.name):  # a set: sort for a stable migration
            out.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
        # Supabase exposes tables through its public API: enable RLS with no policies, so only the server
        # (direct Postgres connection, owner role) can read or write. The anon/public key sees nothing.
        out.append(f"ALTER TABLE {table.name} ENABLE ROW LEVEL SECURITY;")
        out.append("")
    return "\n".join(out)


def import_contingut() -> None:
    from tutor.fitxes import load_llistes
    from tutor.teoria import load_temes, load_teoria

    db.init()
    teoria = load_teoria()
    llistes, exercicis = load_llistes(teoria=teoria)
    print(db.import_contingut(llistes, exercicis, teoria, load_temes()))


def import_generats() -> None:
    db.init()
    n = 0
    for tipus in ("errades", "afirmacions"):
        base = ROOT / "backend" / "generats" / tipus
        for path in sorted(base.glob("*/*/*.json")):
            dades = json.loads(path.read_text(encoding="utf-8"))
            font_id, dificultat = path.parent.parent.name, path.parent.name
            db.desa_generat(tipus, f"{tipus}:{dades.get('id', path.stem)}", font_id, dificultat, dades)
            n += 1
    print(f"{n} generated items imported")


def stats() -> None:
    db.init()
    with db.tx() as c:
        for table in db.meta.sorted_tables:
            print(f"{table.name:20s} {c.execute(select(func.count()).select_from(table)).scalar_one()}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "stats"
    {"schema": lambda: print(schema()), "import": import_contingut, "import-generats": import_generats,
     "stats": stats}[cmd]()
